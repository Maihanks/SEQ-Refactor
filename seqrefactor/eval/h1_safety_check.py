"""Task A (Working Brief Phase 5): H1 safety statistics, reproducible sanity check.

Recomputes the H1 safety comparison (SEQ-REFACTOR yields fewer cascading
violations than a comparator strategy) from the raw per-subject data already
committed in this repository, for both the prespecified comparator
(SEQ-REFACTOR vs. unordered) and the mechanism-exposing comparator
(SEQ-REFACTOR vs. impact-only). It writes a human-readable audit trail to
``evaluation/H1_SAFETY.md`` and a machine-readable ``evaluation/table_h1_safety.csv``.

Reuses ``seqrefactor.eval.stats.paired_test`` exclusively -- the one reviewed
Wilcoxon signed-rank utility every hypothesis test in this repository routes
through -- and does not hand-roll a second implementation.

Raw data sources (all already committed, none regenerated by this script):

- ``evaluation/table2_ablation.csv``: per-subject, per-strategy
  ``cascading_violations`` for the 28-subject corpus (8 strategies, baseline
  generator). This is the source of the corpus means the paper cites
  (impact-only 7.54, unordered 0.96, SEQ-REFACTOR 0.00) -- independently
  re-verified below, not assumed.
- ``evaluation/phase4_e1_raw_runs.json``: the raw ``RunReport``s behind the
  E1 impact-score ablation (Working Brief Phase 4), specifically the
  ``A5_all_three_default`` configuration -- the paper's own default impact
  weights (alpha=0.4, beta=0.4, gamma=0.2) -- used here to recompute the
  early-quality AUC comparison (SEQ-REFACTOR vs. topology-only) fresh, from
  committed per-step trajectories, for the Holm adjustment below.
- ``evaluation/table3_depmass.csv``: per-subject structural dependency mass
  (H4). Every row's ``co_resolution_events``/``cascading_violation_events``
  is 0 (the realised-event columns were never populated for this run, see
  ``eval/depmass.py``'s own module docstring), so the avoided-negative-mass
  and forgone-positive-mass quantities ``eval.depmass.wilcoxon_h4`` would
  compute reduce exactly to ``negative_mass`` and ``positive_mass``
  themselves (rate = 0 / edges = 0, so ``mass * (1 - 0) = mass``) -- this
  script asserts that precondition explicitly before relying on it, rather
  than assuming it silently.

The one rule that cannot be broken (brief's own wording): report whatever
the analysis produces. Nothing here is rounded, relabelled, or adjusted to
match the paper's currently stated numbers.
"""

from __future__ import annotations

import csv
import json
from pathlib import Path

import numpy as np

from seqrefactor.eval.stats import PairedTestResult, paired_test
from seqrefactor.model import RunReport
from seqrefactor.report import auc_quality_trajectory

EVAL_DIR = Path(__file__).resolve().parent.parent.parent / "evaluation"
TABLE2_PATH = EVAL_DIR / "table2_ablation.csv"
TABLE3_PATH = EVAL_DIR / "table3_depmass.csv"
E1_RAW_PATH = EVAL_DIR / "phase4_e1_raw_runs.json"
REPORT_PATH = EVAL_DIR / "H1_SAFETY.md"
TABLE_OUT_PATH = EVAL_DIR / "table_h1_safety.csv"

SEQREFACTOR_SEED = 20260101
WILCOXON_EXACT_MAX_N = 50  # scipy 1.18 wilcoxon docs: method='auto' picks 'exact' at or below this


def _load_table2_cascading_violations() -> dict[str, dict[str, int]]:
    """subject -> {strategy: cascading_violations}, from the committed
    28-subject, 8-strategy ablation matrix."""
    by_subject: dict[str, dict[str, int]] = {}
    with TABLE2_PATH.open("r", encoding="utf-8", newline="") as fh:
        for row in csv.DictReader(fh):
            by_subject.setdefault(row["subject"], {})[row["strategy"]] = int(
                row["cascading_violations"]
            )
    return by_subject


def _paired_cascading(strategy_a: str, strategy_b: str) -> tuple[list[str], list[int], list[int]]:
    by_subject = _load_table2_cascading_violations()
    subjects = sorted(
        s for s, strategies in by_subject.items() if strategy_a in strategies and strategy_b in strategies
    )
    a_vals = [by_subject[s][strategy_a] for s in subjects]
    b_vals = [by_subject[s][strategy_b] for s in subjects]
    return subjects, a_vals, b_vals


def _load_e1_a5_auc() -> tuple[list[str], list[float], list[float]]:
    """SEQ-REFACTOR vs. topology-only early-quality AUC, recomputed fresh from
    the committed E1 raw RunReports at the paper's default impact weights."""
    data = json.loads(E1_RAW_PATH.read_text(encoding="utf-8"))
    runs = [RunReport.model_validate(r) for r in data["A5_all_three_default"]]
    seq = {r.subject: r for r in runs if r.strategy == "seqrefactor"}
    topo = {r.subject: r for r in runs if r.strategy == "topo_only"}
    subjects = sorted(set(seq) & set(topo))
    seq_auc = [auc_quality_trajectory(seq[s]) for s in subjects]
    topo_auc = [auc_quality_trajectory(topo[s]) for s in subjects]
    return subjects, seq_auc, topo_auc


def _load_table3_masses() -> tuple[list[str], list[float], list[float]]:
    """Avoided-negative-mass vs. forgone-positive-mass (H4), which reduce
    exactly to negative_mass/positive_mass given this table's all-zero
    realised-event columns -- asserted, not assumed."""
    subjects: list[str] = []
    negative: list[float] = []
    positive: list[float] = []
    with TABLE3_PATH.open("r", encoding="utf-8", newline="") as fh:
        for row in csv.DictReader(fh):
            co_res = int(row["co_resolution_events"])
            casc = int(row["cascading_violation_events"])
            if co_res != 0 or casc != 0:
                raise RuntimeError(
                    f"subject {row['subject']!r} has nonzero realised co_resolution_events "
                    f"({co_res}) or cascading_violation_events ({casc}); this script's shortcut "
                    "(avoided_negative_mass == negative_mass, forgone_positive_mass == "
                    "positive_mass) no longer holds -- recompute H4 via eval.depmass.wilcoxon_h4 "
                    "with the real graph edge counts instead of taking this shortcut."
                )
            subjects.append(row["subject"])
            negative.append(float(row["negative_mass"]))
            positive.append(float(row["positive_mass"]))
    order = sorted(range(len(subjects)), key=lambda i: subjects[i])
    subjects = [subjects[i] for i in order]
    negative = [negative[i] for i in order]
    positive = [positive[i] for i in order]
    return subjects, negative, positive


def _pos_neg_zero(diffs: list[float]) -> tuple[int, int, int]:
    pos = sum(1 for d in diffs if d > 0)
    neg = sum(1 for d in diffs if d < 0)
    zero = sum(1 for d in diffs if d == 0)
    return pos, neg, zero


def _wilcoxon_method_note(nonzero_diffs: np.ndarray) -> str:
    n_nonzero = len(nonzero_diffs)
    ties = n_nonzero - len(set(np.abs(nonzero_diffs).tolist()))
    if n_nonzero == 0:
        return "no nonzero differences; the test is degenerate (see below)."
    method = "exact" if n_nonzero <= WILCOXON_EXACT_MAX_N else "asymptotic"
    tie_note = (
        f"{ties} tie(s) among the {n_nonzero} nonzero absolute differences"
        if ties
        else "no ties among the nonzero absolute differences"
    )
    return (
        f"method='{method}' (scipy.stats.wilcoxon's default method='auto': exact when the "
        f"number of nonzero paired differences ({n_nonzero}) is <= {WILCOXON_EXACT_MAX_N}, "
        f"asymptotic otherwise); {tie_note}."
    )


def h1_report(
    subjects: list[str], seq: list[int], comparator: list[int], comparator_label: str
) -> dict:
    """Full nine-item audit trail for one H1 comparator (SEQ vs. ``comparator_label``)."""
    diffs = [c - s for s, c in zip(seq, comparator)]
    pos, neg, zero = _pos_neg_zero(diffs)
    result: PairedTestResult = paired_test(comparator, seq, direction="greater", seed=SEQREFACTOR_SEED)

    diffs_arr = np.array(comparator) - np.array(seq)
    nonzero = diffs_arr[diffs_arr != 0]
    method_note = _wilcoxon_method_note(nonzero)

    return {
        "comparator_label": comparator_label,
        "subjects": subjects,
        "seq": seq,
        "comparator": comparator,
        "diffs": diffs,
        "pos": pos,
        "neg": neg,
        "zero": zero,
        "zero_method": "wilcox (paired_test's fixed choice: zero-differences are discarded before ranking)",
        "method_note": method_note,
        "result": result,
        "direction": "one-sided: SEQ-REFACTOR has fewer cascading violations than "
        f"{comparator_label} (H_alt: {comparator_label} - SEQ-REFACTOR > 0)",
    }


def holm_adjust(named_pvalues: list[tuple[str, float]]) -> list[tuple[str, float, float]]:
    """Standard sequential Holm-Bonferroni step-down procedure.

    Sort ascending; adjusted_i = max(adjusted_1..i-1, min(1, (m - rank) * p_i))
    where rank is the 0-indexed position in the sorted order -- the running
    max enforces the procedure's required monotonicity. Returns results in
    the original input order.
    """
    m = len(named_pvalues)
    order = sorted(range(m), key=lambda i: named_pvalues[i][1])
    adjusted = [0.0] * m
    running_max = 0.0
    for rank, idx in enumerate(order):
        _, p = named_pvalues[idx]
        candidate = min(1.0, (m - rank) * p)
        running_max = max(running_max, candidate)
        adjusted[idx] = running_max
    return [(named_pvalues[i][0], named_pvalues[i][1], adjusted[i]) for i in range(m)]


def _fmt(value: float | None, digits: int = 6) -> str:
    return f"{value:.{digits}g}" if value is not None else "n/a"


def _render_comparator(report: dict) -> list[str]:
    r: PairedTestResult = report["result"]
    lines = [
        f"### SEQ-REFACTOR vs. {report['comparator_label']}",
        "",
        f"Direction tested: {report['direction']}",
        "",
        "**1. Raw paired values (cascading_violations per subject, from "
        "`evaluation/table2_ablation.csv`)**",
        "",
        "| subject | seqrefactor | " + report["comparator_label"] + " | diff (comparator - seq) |",
        "| --- | --- | --- | --- |",
    ]
    for s, sv, cv, d in zip(report["subjects"], report["seq"], report["comparator"], report["diffs"]):
        lines.append(f"| {s} | {sv} | {cv} | {d} |")
    lines += [
        "",
        "**2. Paired differences**: listed in the table above (column `diff`).",
        "",
        f"**3. Positive / negative / zero differences**: "
        f"positive={report['pos']}, negative={report['neg']}, zero={report['zero']} "
        f"(n={len(report['subjects'])} total).",
        "",
        f"**4. Wilcoxon signed-rank statistic and zero/tie handling**: "
        f"statistic={_fmt(r.statistic)}. zero_method={report['zero_method']}. {report['method_note']}",
        "",
        f"**5. p-value**: {_fmt(r.p_value)}. {report['method_note'].split(';')[0]}.",
        "",
        f"**6. Matched-pairs rank-biserial effect size**: r={_fmt(r.effect_size_r)}. "
        "Formula (`seqrefactor/eval/stats.py`): r = (W+ - W-) / (W+ + W-), where W+ is the "
        "sum of ranks of the positive nonzero differences and W- the sum of ranks of the "
        "negative nonzero differences (ranks computed over |nonzero differences|). "
        "r = 1.0 exactly and only when every nonzero paired difference favours SEQ-REFACTOR "
        "(W- = 0); the positive/negative counts in item 3 above make this true or false directly.",
        "",
        f"**7. Mean paired difference and bootstrap 95% CI**: "
        f"mean_difference={_fmt(r.mean_difference)}, "
        f"95% CI=[{_fmt(r.ci_low)}, {_fmt(r.ci_high)}] "
        f"(percentile bootstrap, 2000 resamples, seed={SEQREFACTOR_SEED}).",
        "",
        f"**8. Direction tested**: {report['direction']}.",
        "",
        f"**9. Supported at p<0.05**: {r.supported}. Note: {r.note}",
        "",
    ]
    return lines


def main() -> None:
    unordered_subjects, seq_vs_unordered_seq, seq_vs_unordered_cmp = _paired_cascading(
        "seqrefactor", "unordered"
    )
    unordered_report = h1_report(
        unordered_subjects, seq_vs_unordered_seq, seq_vs_unordered_cmp, "unordered"
    )

    impact_subjects, seq_vs_impact_seq, seq_vs_impact_cmp = _paired_cascading(
        "seqrefactor", "impact_only"
    )
    impact_report = h1_report(impact_subjects, seq_vs_impact_seq, seq_vs_impact_cmp, "impact_only")

    # Holm adjustment across the three prespecified hypothesis tests (brief's own
    # naming): H1 safety (the prespecified SEQ-vs-unordered comparator above),
    # H2 early quality (SEQ-REFACTOR vs. topology-only AUC, this repo's
    # H3_higher_auc_vs_topo_only), H3 efficiency (the dependency-mass comparison,
    # this repo's H4_dependency_mass) -- see module docstring for why these three
    # map onto the brief's "H1 safety / H2 early quality / H3 efficiency" labels
    # (they are exactly the three headline p-values (0.042, 0.0009, 0.486) this
    # repository has been reporting and re-verifying since Phase 3c).
    auc_subjects, seq_auc, topo_auc = _load_e1_a5_auc()
    auc_result = paired_test(seq_auc, topo_auc, direction="greater", seed=SEQREFACTOR_SEED)

    mass_subjects, avoided_negative, forgone_positive = _load_table3_masses()
    mass_result = paired_test(avoided_negative, forgone_positive, direction="greater", seed=SEQREFACTOR_SEED)

    raw_pvalues = [
        ("H1_safety (SEQ vs unordered, cascading violations)", unordered_report["result"].p_value),
        ("H2_early_quality (SEQ vs topo_only, AUC, A5 default weights)", auc_result.p_value),
        ("H3_efficiency (avoided-negative-mass vs forgone-positive-mass)", mass_result.p_value),
    ]
    if any(p is None for _, p in raw_pvalues):
        missing = [name for name, p in raw_pvalues if p is None]
        raise RuntimeError(f"cannot Holm-adjust: p-value missing/degenerate for {missing}")
    holm_results = holm_adjust(raw_pvalues)

    lines = [
        "# H1 safety statistics: reproducible sanity check",
        "",
        "Generated by `seqrefactor/eval/h1_safety_check.py` (Working Brief Phase 5, Task A). "
        "Reuses `seqrefactor.eval.stats.paired_test` exclusively; nothing here is a second "
        "Wilcoxon implementation. Every number below is recomputed from the committed raw "
        "per-subject data listed in that script's module docstring -- none is copied or "
        "hand-adjusted from the paper.",
        "",
        "## Prespecified comparator: SEQ-REFACTOR vs. unordered",
        "",
    ]
    lines += _render_comparator(unordered_report)
    lines += [
        "## Mechanism-exposing comparator: SEQ-REFACTOR vs. impact-only",
        "",
        "(For information -- not part of the Holm adjustment below, which is over the three",
        "prespecified hypothesis tests only.)",
        "",
    ]
    lines += _render_comparator(impact_report)

    lines += [
        "## Holm-adjusted p-values across the three prespecified hypothesis tests",
        "",
        "Standard sequential Holm-Bonferroni step-down procedure over "
        "[H1_safety, H2_early_quality, H3_efficiency]:",
        "",
        "| hypothesis | raw p | Holm-adjusted p | source |",
        "| --- | --- | --- | --- |",
    ]
    sources = {
        "H1_safety (SEQ vs unordered, cascading violations)": (
            "recomputed above, this script, from `evaluation/table2_ablation.csv`"
        ),
        "H2_early_quality (SEQ vs topo_only, AUC, A5 default weights)": (
            f"recomputed by this script from `evaluation/phase4_e1_raw_runs.json` "
            f"(`A5_all_three_default` configuration, n={len(auc_subjects)} subjects); "
            f"matches this repo's `H3_higher_auc_vs_topo_only` in `report.hypothesis_tests`"
        ),
        "H3_efficiency (avoided-negative-mass vs forgone-positive-mass)": (
            f"recomputed by this script from `evaluation/table3_depmass.csv` "
            f"(n={len(mass_subjects)} subjects); matches this repo's `H4_dependency_mass`"
        ),
    }
    for name, raw_p, adj_p in holm_results:
        lines.append(f"| {name} | {_fmt(raw_p)} | {_fmt(adj_p)} | {sources[name]} |")

    lines += [
        "",
        f"H2_early_quality full result: n={auc_result.n}, statistic={_fmt(auc_result.statistic)}, "
        f"p={_fmt(auc_result.p_value)}, effect_size_r={_fmt(auc_result.effect_size_r)}, "
        f"mean_difference={_fmt(auc_result.mean_difference)}, "
        f"ci=[{_fmt(auc_result.ci_low)}, {_fmt(auc_result.ci_high)}], supported={auc_result.supported}.",
        "",
        f"H3_efficiency full result: n={mass_result.n}, statistic={_fmt(mass_result.statistic)}, "
        f"p={_fmt(mass_result.p_value)}, effect_size_r={_fmt(mass_result.effect_size_r)}, "
        f"mean_difference={_fmt(mass_result.mean_difference)}, "
        f"ci=[{_fmt(mass_result.ci_low)}, {_fmt(mass_result.ci_high)}], supported={mass_result.supported}. "
        "Computed as paired_test(negative_mass, positive_mass) per subject "
        "(`evaluation/table3_depmass.csv`), which is exactly avoided_negative_mass vs. "
        "forgone_positive_mass since every row's realised co_resolution/cascading event "
        "count is 0 (asserted in `_load_table3_masses`, not assumed).",
        "",
    ]

    REPORT_PATH.write_text("\n".join(lines) + "\n", encoding="utf-8")

    csv_rows = []
    for report, label in ((unordered_report, "unordered"), (impact_report, "impact_only")):
        r = report["result"]
        csv_rows.append(
            {
                "comparator": label,
                "n": len(report["subjects"]),
                "positive": report["pos"],
                "negative": report["neg"],
                "zero": report["zero"],
                "statistic": r.statistic,
                "p_value": r.p_value,
                "effect_size_r": r.effect_size_r,
                "mean_difference": r.mean_difference,
                "ci_low": r.ci_low,
                "ci_high": r.ci_high,
                "supported": r.supported,
            }
        )
    for name, raw_p, adj_p in holm_results:
        csv_rows.append(
            {
                "comparator": name,
                "n": "",
                "positive": "",
                "negative": "",
                "zero": "",
                "statistic": "",
                "p_value": raw_p,
                "effect_size_r": "",
                "mean_difference": "",
                "ci_low": "",
                "ci_high": "",
                "supported": f"holm_adjusted_p={adj_p}",
            }
        )
    with TABLE_OUT_PATH.open("w", newline="", encoding="utf-8") as fh:
        writer = csv.DictWriter(fh, fieldnames=list(csv_rows[0].keys()))
        writer.writeheader()
        writer.writerows(csv_rows)

    u = unordered_report["result"]
    print(f"SEQ-vs-unordered: n={u.n} p={_fmt(u.p_value)} r={_fmt(u.effect_size_r)} "
          f"mean_diff={_fmt(u.mean_difference)} pos={unordered_report['pos']} "
          f"neg={unordered_report['neg']} zero={unordered_report['zero']} supported={u.supported}")
    i = impact_report["result"]
    print(f"SEQ-vs-impact_only: n={i.n} p={_fmt(i.p_value)} r={_fmt(i.effect_size_r)} "
          f"mean_diff={_fmt(i.mean_difference)} pos={impact_report['pos']} "
          f"neg={impact_report['neg']} zero={impact_report['zero']} supported={i.supported}")
    for name, raw_p, adj_p in holm_results:
        print(f"Holm: {name}: raw_p={_fmt(raw_p)} adjusted_p={_fmt(adj_p)}")
    print(f"wrote {REPORT_PATH} and {TABLE_OUT_PATH}")


if __name__ == "__main__":
    main()
